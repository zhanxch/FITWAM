"""EveRobot manifest: episode-level metadata for fast dataset initialization.

The manifest is a JSON file that pre-computes episode boundaries, video paths,
task strings, and per-episode action/state array paths so ``EveRobotDataset``
does not need to scan parquet files at construction time.

Generated by ``scripts/convert_lerobot_to_everobot.py``.
"""

import json
from pathlib import Path
from typing import Any, Dict, List, Optional


def build_episode_records(
    dataset_dir: str,
    *,
    video_keys: List[str],
    parquet_path_template: str = "data/chunk-{episode_chunk:03d}/episode_{episode_index:06d}.parquet",
    video_path_template: str = "videos/chunk-{episode_chunk:03d}/{video_key}/episode_{episode_index:06d}.mp4",
    chunks_size: int = 1000,
) -> List[Dict[str, Any]]:
    """Scan a LeRobot v2.1 dataset directory and build per-episode records.

    Each record contains: episode_index, length, task, task_index, and relative
    paths to the parquet + per-camera mp4 files.
    """
    ds_root = Path(dataset_dir)

    info_path = ds_root / "meta" / "info.json"
    if not info_path.exists():
        raise FileNotFoundError(f"Missing {info_path}")
    with open(info_path, "r", encoding="utf-8") as f:
        info = json.load(f)

    total_episodes = int(info["total_episodes"])

    tasks: Dict[int, str] = {}
    tasks_path = ds_root / "meta" / "tasks.jsonl"
    if tasks_path.exists():
        with open(tasks_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                row = json.loads(line)
                tasks[int(row["task_index"])] = row["task"]

    episode_lengths: Dict[int, int] = {}
    episodes_path = ds_root / "meta" / "episodes.jsonl"
    if episodes_path.exists():
        with open(episodes_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                row = json.loads(line)
                ep_idx = int(row["episode_index"])
                episode_lengths[ep_idx] = int(row["length"])

    records: List[Dict[str, Any]] = []
    for ep_idx in range(total_episodes):
        ep_chunk = ep_idx // chunks_size
        length = episode_lengths.get(ep_idx, None)
        if length is None:
            raise ValueError(f"Episode {ep_idx} length not found in episodes.jsonl")

        parquet_rel = parquet_path_template.format(episode_chunk=ep_chunk, episode_index=ep_idx)
        videos_rel = {
            vk: video_path_template.format(
                episode_chunk=ep_chunk,
                video_key=f"observation.images.{vk}",
                episode_index=ep_idx,
            )
            for vk in video_keys
        }

        # Resolve task: LeRobot v2.1 episodes.jsonl has "tasks" list; fallback to single task.
        task_str = ""
        task_index = 0
        if episodes_path.exists():
            with open(episodes_path, "r", encoding="utf-8") as f:
                for line in f:
                    row = json.loads(line.strip())
                    if int(row["episode_index"]) == ep_idx:
                        task_list = row.get("tasks", [])
                        task_str = task_list[0] if task_list else ""
                        break
        if not task_str and tasks:
            task_str = tasks.get(0, "")
            task_index = 0

        records.append(
            {
                "episode_index": ep_idx,
                "episode_chunk": ep_chunk,
                "length": length,
                "task": task_str,
                "task_index": task_index,
                "parquet_path": str(ds_root / parquet_rel),
                "video_paths": {vk: str(ds_root / videos_rel[vk]) for vk in video_keys},
            }
        )

    return records


def save_manifest(
    output_path: str,
    *,
    dataset_dir: str,
    episodes: List[Dict[str, Any]],
    fps: int,
    action_dim: int,
    state_dim: int,
    video_keys: List[str],
    video_resolution: List[int],
    modality: Optional[Dict[str, Any]] = None,
    stats_path: Optional[str] = None,
    extra: Optional[Dict[str, Any]] = None,
) -> str:
    """Write the EveRobot manifest JSON."""
    manifest = {
        "format": "everobot",
        "version": 1,
        "source_dataset_dir": str(Path(dataset_dir).resolve()),
        "fps": int(fps),
        "action_dim": int(action_dim),
        "state_dim": int(state_dim),
        "video_keys": list(video_keys),
        "video_resolution": list(video_resolution),
        "num_episodes": len(episodes),
        "modality": modality or {},
        "stats_path": stats_path,
        "episodes": episodes,
    }
    if extra:
        manifest.update(extra)

    out = Path(output_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=True, indent=2)
    return str(out)


def load_manifest(manifest_path: str) -> Dict[str, Any]:
    """Load an EveRobot manifest JSON."""
    with open(manifest_path, "r", encoding="utf-8") as f:
        return json.load(f)
