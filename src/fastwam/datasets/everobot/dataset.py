"""EveRobotDataset: episode-level sampling with first-frame dropout.

Subclass of ``RobotVideoDataset`` that treats each episode (one mp4 per camera)
as a training sample, following DiffSynth-Studio's WAN fine-tuning style.

Key differences from the standard ``RobotVideoDataset``:

* **Sample unit = episode** (not frame window). ``__len__`` returns
  ``num_episodes * samples_per_episode``.
* **First-frame dropout** replaces ``dataset_repeat``. Instead of seeing the
  identical clip N times, each sub-clip drops a configurable number of leading
  frames, producing diverse temporal windows from the same episode.
* All frame loading, multi-camera concatenation, normalization, text-embedding
  caching, and output format are inherited unchanged — only the indexing
  strategy changes.

The output sample dict is identical to ``RobotVideoDataset``, so the existing
``FastWAM.training_loss()`` and ``Wan22Trainer`` work without modification.
"""

import json
import random
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np
import torch

from fastwam.datasets.lerobot.robot_video_dataset import RobotVideoDataset
from fastwam.utils.logging_config import get_logger

from .manifest import load_manifest

logger = get_logger(__name__)


class EveRobotDataset(RobotVideoDataset):
    """Episode-level dataset with first-frame dropout.

    Args:
        manifest_path: Path to ``everobot_manifest.json`` (generated by
            ``scripts/water_plant/convert_lerobot_to_everobot.py``). If ``None``, the
            manifest is built on-the-fly from ``dataset_dirs``.
        drop_first_frames: Number of leading frames to drop from each episode.
            The training window starts at frame ``drop_first_frames`` instead
            of frame 0. Set to 0 for no dropout.
        drop_first_frames_random: If ``True``, the number of dropped frames is
            sampled uniformly from ``[0, drop_first_frames]`` each time, giving
            temporal augmentation. If ``False``, a fixed number is dropped.
        samples_per_episode: Number of sub-clips sampled per episode per epoch
            (replaces DiffSynth's ``dataset_repeat``). With
            ``drop_first_frames_random=True``, each sub-clip sees a different
            temporal window. Set to 1 for one sample per episode.
        **kwargs: All other arguments are forwarded to ``RobotVideoDataset``
            (``dataset_dirs``, ``shape_meta``, ``num_frames``, ``video_size``,
            ``processor``, ``text_embedding_cache_dir``, etc.).
    """

    def __init__(
        self,
        *args,
        manifest_path: Optional[str] = None,
        drop_first_frames: int = 0,
        drop_first_frames_random: bool = False,
        samples_per_episode: int = 1,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)

        if drop_first_frames < 0:
            raise ValueError(f"`drop_first_frames` must be >= 0, got {drop_first_frames}")
        if samples_per_episode < 1:
            raise ValueError(f"`samples_per_episode` must be >= 1, got {samples_per_episode}")

        self.drop_first_frames = int(drop_first_frames)
        self.drop_first_frames_random = bool(drop_first_frames_random)
        self.samples_per_episode = int(samples_per_episode)

        # Build episode index from the underlying BaseLerobotDataset.
        # episode_data_index gives global [from, to) for each episode in this
        # split (train or val). Episodes shorter than num_frames are skipped.
        self._episode_starts: List[int] = []
        self._episode_lengths: List[int] = []
        self._episode_valid_starts: List[List[int]] = []

        num_video_frames = self.num_frames
        ep_from = self.lerobot_dataset.episode_data_index["from"].tolist()
        ep_to = self.lerobot_dataset.episode_data_index["to"].tolist()

        for ep_idx, (frm, to) in enumerate(zip(ep_from, ep_to)):
            length = int(to - frm)
            if length < num_video_frames:
                logger.warning(
                    "Episode %d has %d frames < num_frames=%d; skipping.",
                    ep_idx,
                    length,
                    num_video_frames,
                )
                continue
            max_start = length - num_video_frames
            if self.drop_first_frames_random:
                # Valid starts: [0, min(drop_first_frames, max_start)]
                upper = min(self.drop_first_frames, max_start)
                valid_starts = list(range(0, upper + 1))
            else:
                # Fixed drop: start = drop_first_frames (clamped to max_start)
                start = min(self.drop_first_frames, max_start)
                valid_starts = [start]
            if not valid_starts:
                continue
            self._episode_starts.append(int(frm))
            self._episode_lengths.append(length)
            self._episode_valid_starts.append(valid_starts)

        self._num_valid_episodes = len(self._episode_starts)
        if self._num_valid_episodes == 0:
            raise ValueError(
                "No valid episodes found. All episodes are shorter than "
                f"num_frames={num_video_frames} or have no valid start after dropout."
            )

        logger.info(
            "EveRobotDataset: %d valid episodes, samples_per_episode=%d, "
            "drop_first_frames=%d (random=%s), total_samples=%d",
            self._num_valid_episodes,
            self.samples_per_episode,
            self.drop_first_frames,
            self.drop_first_frames_random,
            len(self),
        )

    def __len__(self) -> int:
        return self._num_valid_episodes * self.samples_per_episode

    def _sample_window_start(self, valid_starts: List[int]) -> int:
        """Pick a window start from the valid starts list."""
        if len(valid_starts) == 1:
            return valid_starts[0]
        return random.choice(valid_starts)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        if idx >= len(self):
            raise IndexError(f"Index {idx} out of bounds {len(self)}.")

        ep_local = idx // self.samples_per_episode
        # _sample_within_episode = idx % self.samples_per_episode

        global_start = self._episode_starts[ep_local]
        valid_starts = self._episode_valid_starts[ep_local]
        window_start = self._sample_window_start(valid_starts)
        global_frame_idx = global_start + window_start

        try:
            data = self._get(global_frame_idx)
        except Exception as e:
            logger.warning(
                "EveRobot: error loading episode %d window_start=%d global_idx=%d: %s. "
                "Retrying with episode 0.",
                ep_local,
                window_start,
                global_frame_idx,
                e,
            )
            data = self._get(self._episode_starts[0])

        data["everobot_episode_index"] = ep_local
        data["everobot_window_start"] = window_start
        return data
